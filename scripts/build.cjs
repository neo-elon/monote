const fs = require('node:fs');
const esbuild = require('esbuild');
fs.mkdirSync('vendor', { recursive: true });
const packages = ['supabase-js', 'auth-js', 'functions-js', 'postgrest-js', 'realtime-js', 'storage-js'].map(name => '@supabase/' + name).concat('abortcontroller-polyfill');
fs.writeFileSync('vendor/LICENSES.txt', packages.map(name => name + '\n\n' + fs.readFileSync('node_modules/' + name + '/LICENSE', 'utf8')).join('\n\n---\n\n'));
// Transform the official browser bundle without changing auth/session semantics.
for (const [input, output] of [
  ['node_modules/@supabase/supabase-js/dist/umd/supabase.js', 'vendor/supabase.js'],
  ['node_modules/abortcontroller-polyfill/dist/polyfill-patch-fetch.js', 'vendor/abortcontroller.js'],
  ['app-cover.js', 'app-compat.js']
]) {
  const result = esbuild.transformSync(fs.readFileSync(input, 'utf8'), {
    target: 'chrome55', minify: input.includes('node_modules'), legalComments: 'inline'
  });
  fs.writeFileSync(output, '// Generated by npm run build; do not edit.\n' + result.code);
}
